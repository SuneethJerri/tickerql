/** The first three slots are the only ones that validate all-pairs. */
export const SCATTER_HUE_CAP = 3;

/** Colour for a sector, assigned by position in the caller's own `sectors`
 *  list rather than a fixed global order. Past the categorical cap it returns
 *  null so the caller must decide (fold to "Other", or facet); it never wraps
 *  around and reuses a hue. */
export function sectorColor(
  sector: string,
  sectors: readonly string[],
  theme: ThemeName,
): string | null {
  const index = sectors.indexOf(sector);
  const slots = CATEGORICAL[theme];
  if (index < 0 || index >= slots.length) return null;
  return slots[index]!;
}

/** Neutral for anything past the categorical cap. */
export function otherColor(theme: ThemeName): string {
  return CONTEXT_GREYS[theme][0]!;
}

/** Slots 1 and 2: the scatter is an all-pairs form, and those are inside the
 *  validated three. */
export function assetTypeColor(assetType: string, theme: ThemeName): string {
  return assetType === "crypto" ? CATEGORICAL[theme][1] : CATEGORICAL[theme][0];
}

/** Series colours for an EMPHASIS form, not a categorical one: the close price
 *  is the subject and the moving averages are context. Giving each MA its own
 *  categorical hue would imply four peer series. */
export function emphasisColors(theme: ThemeName) {
  // Keyed, not a ternary on "light": a ternary returns something plausible for
  // a theme it has never heard of, and compiles.
  return { primary: PRIMARY[theme], context: [...CONTEXT_GREYS[theme]] };
}

/** Continuous mix across the diverging scale. `t` in [-1, 1]. */
export function divergingColor(t: number, theme: ThemeName): string {
  const { negative, mid, positive } = DIVERGING[theme];
  const clamped = Math.max(-1, Math.min(1, t));
  const target = clamped < 0 ? negative : positive;
  return mixHex(mid, target, Math.abs(clamped));
}

function mixHex(from: string, to: string, amount: number): string {
  const a = hexToRgb(from);
  const b = hexToRgb(to);
  const mix = (x: number, y: number) => Math.round(x + (y - x) * amount);
  return rgbToHex(mix(a[0], b[0]), mix(a[1], b[1]), mix(a[2], b[2]));
}

function hexToRgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function rgbToHex(r: number, g: number, b: number): string {
  return "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");
}

/** Relative luminance, for choosing ink that clears contrast inside a filled cell. */
export function inkOn(background: string): string {
  const [r, g, b] = hexToRgb(background).map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  }) as [number, number, number];
  const luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return luminance > 0.45 ? "#0b0b0b" : "#ffffff";
}

