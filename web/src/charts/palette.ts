/**
 * Chart palettes, one per theme, searched against that theme's own surface.
 *
 * Four gates, all measured by web/scripts/build_palettes.mjs: adjacent-pair
 * separation under simulated CVD (>= 8.0), under normal vision (>= 15.0),
 * contrast against the surface (>= 3.0:1), and OKLab dE >= 15 from all four
 * accents in the base, so a button is never the colour of a line.
 *
 * Eight slots pass ADJACENT (lines, bars, stacks); only the first three pass
 * ALL-PAIRS (scatter, small multiples). `sectorColor` returns null past eight
 * rather than reusing a hue.
 *
 * To change a colour, edit the generator and re-run it. Do not hand-edit the
 * tables below; it prints them along with the report each set passed.
 */
import type { ThemeName } from "../theme";

/** Chart code keys on the theme, not on a light/dark base: the surface is what
 *  a series colour has to survive. */
export type { ThemeName } from "../theme";

