/** The one hue behind every sparkline, every small-multiple panel and the
 *  close-price line: by area the most visible colour in the app.
 *
 *  All five are chosen jointly, one member per theme, 8^5 combinations searched
 *  with dE >= 15 between every pair as a hard floor and the per-theme target
 *  hue deciding among what clears it. Chosen independently they converge on the
 *  same navy and four themes draw identical charts. check_palettes.mjs
 *  re-measures the floor. */
const PRIMARY = {
  light: "#1246ac",
  dark: "#22a3d0",
  midnight: "#ca7b2f",
  graphite: "#bf649a",
  sepia: "#76971b",
} as const;

/** Context neutrals, carrying the surface's own hue at near-zero chroma, so
 *  Sepia's are warm and Midnight's cool rather than one grey serving both.
 *  The moving averages behind an emphasised close price are these. */
const CONTEXT_GREYS = {
  light: ["#717579", "#91969a", "#b0b5b9"],
  dark: ["#84837e", "#666661", "#4d4d48"],
  midnight: ["#818388", "#64666b", "#4b4d52"],
  graphite: ["#828288", "#65656b", "#4c4c51"],
  sepia: ["#76746f", "#979590", "#b6b4af"],
} as const;

/** Diverging poles for correlation. The midpoint has to read as "nothing" on
 *  its surface: a scale whose centre looks like a colour makes zero
 *  correlation look like a result. */
const DIVERGING = {
  light: { negative: "#3379ce", mid: "#ebeff2", positive: "#cb584f" },
  dark: { negative: "#5391de", mid: "#31312d", positive: "#cb685e" },
  midnight: { negative: "#5391de", mid: "#2f3033", positive: "#cb685e" },
  graphite: { negative: "#5b96e0", mid: "#303033", positive: "#d86b61" },
  sepia: { negative: "#3379ce", mid: "#f0eeea", positive: "#cb584f" },
} as const;
